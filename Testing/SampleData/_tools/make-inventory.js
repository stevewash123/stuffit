// Builds INVENTORY.md from the keys that already exist. Run from anywhere:  node _tools/make-inventory.js
// Sources: receipts/pdf-as-jpg/answer-key-by-item.csv (receipts, lines, models), receipts/paper-photo/truth.json, warranties-from-receipts/index.csv,
// warranties/index.csv, receipts/pdf-series-94-103-returns-manifest.csv, index.csv (emails, photos), the folders themselves.
const fs = require('fs'), path = require('path');
const R = path.join(__dirname, '..');
const rd = (p) => fs.readFileSync(path.join(R, p), 'utf8').replace(/^﻿/, '');
function csv(text) {
  const rows = []; let row = [], cur = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"') { if (text[i + 1] === '"') { cur += '"'; i++; } else q = false; } else cur += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(cur); cur = ''; }
    else if (c === '\n') { row.push(cur.replace(/\r$/, '')); rows.push(row); row = []; cur = ''; }
    else cur += c;
  }
  if (cur || row.length) { row.push(cur.replace(/\r$/, '')); rows.push(row); }
  const head = rows.shift();
  return rows.filter((r) => r.length > 1).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ''])));
}
const list = (d, ext) => fs.existsSync(path.join(R, d)) ? fs.readdirSync(path.join(R, d)).filter((f) => ext.test(f)) : [];
const norm = (s) => (s || '').toUpperCase().replace(/[^A-Z0-9]/g, '');
const base = (f) => f.replace(/\.(pdf|jpg|png|eml|html)$/i, '');
const num = (f) => { const m = /^(\d+)-/.exec(f); return m ? +m[1] : null; };
const esc = (s) => (s || '').replace(/\|/g, '/').replace(/\s+/g, ' ').trim();

// ---- receipts and their lines
const key = csv(rd('receipts/pdf-as-jpg/answer-key-by-item.csv'));
const receipts = new Map();
for (const r of key) {
  const id = base(r.file);
  if (!receipts.has(id)) receipts.set(id, { id, store: r.store, order: r.order_number, date: r.purchase_date, total: r.total, card: r.payment_last4, cls: r.document_class, note: r.receipt_note, lines: [] });
  if (r.line_no) receipts.get(id).lines.push(r);
}
const pdfs = new Set(list('receipts/pdf', /\.pdf$/i).map(base));
const jpgs = new Set(list('receipts/pdf-as-jpg', /\.jpg$/i).map(base));
const products = (rc) => rc.lines.filter((l) => l.kind === 'product' || l.kind === 'service').map((l) => ({ brand: l.brand, name: l.name, model: l.model_number, kind: l.kind, line: l.line }));

// ---- documents
const wr = csv(rd('warranties-from-receipts/index.csv'));
const wg = csv(rd('warranties/index.csv'));
const returns = csv(rd('receipts/pdf-series-94-103-returns-manifest.csv'));
const idx = csv(rd('index.csv'));
const photoTruth = JSON.parse(rd('receipts/paper-photo/truth.json'));
const photos = Array.isArray(photoTruth) ? photoTruth : Object.entries(photoTruth).map(([k, v]) => ({ file: k, ...v }));

// generic warranty: brand= and model= are inside "expected"
const field = (s, k) => { const m = new RegExp(k + '=([^;,]+)', 'i').exec(s || ''); return m ? m[1].trim() : ''; };
for (const g of wg) { g.brand = field(g.expected, 'brand'); g.model = field(g.expected, 'model'); g.name = path.basename(g.path); }

// ---- links
const byModel = new Map(), byBrand = new Map(), byStore = new Map();
const add = (m, k, v) => { if (!k) return; if (!m.has(k)) m.set(k, []); m.get(k).push(v); };
for (const rc of receipts.values()) {
  add(byStore, norm(rc.store), rc.id);
  for (const p of products(rc)) { add(byModel, norm(p.model), rc.id); add(byBrand, norm(p.brand), rc.id); }
}
const docsForReceipt = (id) => wr.filter((w) => base(w.source_receipt) === id).map((w) => base(w.file).slice(0, 2));
const returnsForReceipt = (id) => { const n = num(id + '-'); return returns.filter((r) => new RegExp('receipt ' + n + '\\b').test(r.about)).map((r) => String(num(r.file))); };
const genericForReceipt = (id) => {
  const rc = receipts.get(id), out = [];
  for (const p of products(rc)) for (const g of wg) {
    if (p.model && g.model && norm(p.model) === norm(g.model)) out.push(g.name + ' (same model)');
    else if (p.brand && g.brand && norm(p.brand) === norm(g.brand) && p.kind === 'product') out.push(g.name + ' (same maker, other model)');
  }
  return [...new Set(out)];
};
// emails that mention a receipt's model number
const emlFiles = ['order-confirmation', 'shipping', 'delivery', 'e-receipt'].flatMap((d) => list('emails/' + d, /\.(eml|html)$/i).map((f) => ({ d, f, t: norm(fs.readFileSync(path.join(R, 'emails', d, f), 'utf8')) })));
const emailsForReceipt = (id) => {
  const rc = receipts.get(id), out = [];
  for (const p of products(rc)) if (p.model && norm(p.model).length >= 5) for (const e of emlFiles) if (e.t.includes(norm(p.model))) out.push(e.d + '/' + e.f);
  return [...new Set(out)];
};

const L = [];
const w = (s = '') => L.push(s);
w('# SampleData inventory');
w();
w('Generated by `_tools/make-inventory.js` from the keys in this tree (answer key, `index.csv` files, manifests). Do not edit by hand: change the key or the script and run `node _tools/make-inventory.js`.');
w('Purpose: show which documents belong together (same item, same maker, same store) because that decides how they move through the workflows in `Stories/TESTING/T2-document-handling-test-plan.md`.');
w();
w('## 1. What is here');
w();
w('| Folder | Files | Format | Key |');
w('|---|---|---|---|');
w(`| receipts/pdf | ${pdfs.size} | PDF receipts, invoices, emailed-receipt printouts | answer key by item (below) |`);
w(`| receipts/pdf-as-jpg | ${jpgs.size} | The same receipts as phone-style images (same names) | answer-key-by-item.csv |`);
w(`| receipts/paper-photo | ${list('receipts/paper-photo', /\.jpg$/i).length} | Real photos of paper receipts | truth.json |`);
w(`| warranties-from-receipts | ${list('warranties-from-receipts', /\.pdf$/i).length} | Plan / warranty documents, each built from a receipt | index.csv (col source_receipt) |`);
w(`| warranties | ${list('warranties', /\.(pdf|png)$/i).length} | Generic warranty fixtures, no receipt tie by design (a few share a model with a receipt) | index.csv |`);
for (const d of ['order-confirmation', 'shipping', 'delivery', 'e-receipt']) w(`| emails/${d} | ${list('emails/' + d, /\.(eml|html)$/i).length} | Retailer emails | index.csv |`);
w();
w(`Receipts in the answer key: ${receipts.size}. Receipts with a PDF but no image twin: ${[...pdfs].filter((x) => !jpgs.has(x)).join(', ') || 'none'}. Images with no PDF: ${[...jpgs].filter((x) => !pdfs.has(x) && receipts.has(x)).join(', ') || 'none'}.`);
w();

w('## 2. Receipts and everything linked to them');
w();
w('Columns: **Docs** = plan or warranty documents built from this receipt (`warranties-from-receipts` numbers). **Returns** = return/refund receipts that refer back to this one. **Generic warranty** = a file in `warranties/` for the same model (or same maker). **Emails** = sample emails that mention the same model number. **Twin** = image copy exists.');
w();
w('| # | Receipt | Store | Date | Card | Items (brand model) | Docs | Returns | Generic warranty | Emails | Twin |');
w('|---|---|---|---|---|---|---|---|---|---|---|');
const order = [...receipts.values()].sort((a, b) => (num(a.id) ?? 1e6) - (num(b.id) ?? 1e6) || a.id.localeCompare(b.id));
for (const rc of order) {
  const items = products(rc).filter((p) => p.kind === 'product').map((p) => esc([p.brand, p.model || p.name].filter(Boolean).join(' '))).join('; ');
  const plan = products(rc).some((p) => p.kind === 'service') ? ' (+plan line)' : '';
  w(`| ${num(rc.id) ?? ''} | ${esc(rc.id)} | ${esc(rc.store)} | ${rc.date} | ${rc.card} | ${items}${plan} | ${docsForReceipt(rc.id).join(', ')} | ${returnsForReceipt(rc.id).join(', ')} | ${genericForReceipt(rc.id).join('; ')} | ${emailsForReceipt(rc.id).slice(0, 3).join('; ')} | ${jpgs.has(rc.id) ? 'yes' : 'no'} |`);
}
w();

w('## 3. Plan and warranty documents built from receipts');
w();
w('| Doc | Kind | Source receipt | Item (model) | Plan # | Term | Confidence | Source receipt also has |');
w('|---|---|---|---|---|---|---|---|');
for (const x of wr) {
  const rid = base(x.source_receipt), rc = receipts.get(rid);
  const sameStore = rc ? [...(byStore.get(norm(rc.store)) || [])].filter((i) => i !== rid).length : 0;
  w(`| ${esc(base(x.file))} | ${x.kind} | ${num(rid)} ${esc(rc ? rc.store : '')} | ${esc(x.product)} (${esc(x.model)}) | ${esc(x.plan_no)} | ${esc(x.term)} | ${x.confidence} | ${returnsForReceipt(rid).length ? 'return ' + returnsForReceipt(rid).join(', ') + '; ' : ''}${sameStore} other receipt(s) from this store |`);
}
w();

w('## 4. Generic warranties (`warranties/`) and what they connect to');
w();
w('| File | Kind | Brand | Model | Same-model receipts | Same-maker receipts |');
w('|---|---|---|---|---|---|');
for (const g of wg) {
  const sm = (byModel.get(norm(g.model)) || []).map((i) => num(i)).filter(Boolean);
  const mk = (byBrand.get(norm(g.brand)) || []).map((i) => num(i)).filter(Boolean).filter((n) => !sm.includes(n));
  w(`| ${esc(g.name)} | ${g.kind} | ${esc(g.brand)} | ${esc(g.model)} | ${[...new Set(sm)].join(', ') || 'none'} | ${[...new Set(mk)].join(', ') || 'none'} |`);
}
w();

w('## 5. Groups that matter for workflows');
w();
w('### Same store, several receipts (a user shops where they shop)');
w();
w('| Store | Receipts |');
w('|---|---|');
const stores = [...byStore.entries()].filter(([, v]) => v.length > 1).sort((a, b) => b[1].length - a[1].length);
for (const [k, v] of stores) { const nm = receipts.get(v[0]).store; w(`| ${esc(nm)} | ${v.map((i) => num(i)).filter(Boolean).join(', ')} |`); }
w();
w('### Same maker, several receipts or documents');
w();
w('| Maker | Receipts | Warranty docs (from receipts) | Generic warranties |');
w('|---|---|---|---|');
const makers = [...byBrand.entries()].filter(([k, v]) => k && (v.length > 1 || wg.some((g) => norm(g.brand) === k))).sort((a, b) => b[1].length - a[1].length);
for (const [k, v] of makers) {
  const display = (() => { for (const rc of receipts.values()) for (const p of products(rc)) if (norm(p.brand) === k) return p.brand; return k; })();
  const docs = wr.filter((x) => norm(x.product.split(/s+/)[0]) === k || v.some((i) => base(x.source_receipt) === i)).map((x) => base(x.file).slice(0, 2));
  const gen = wg.filter((g) => norm(g.brand) === k).map((g) => g.name);
  w(`| ${esc(display)} | ${[...new Set(v.map((i) => num(i)).filter(Boolean))].join(', ')} | ${[...new Set(docs)].join(', ')} | ${gen.join('; ')} |`);
}
w();
w('### Same item (same model) across receipts and documents');
w();
w('| Model | Receipts | Docs (from receipts) | Generic warranty | Returns |');
w('|---|---|---|---|---|');
for (const [k, v] of [...byModel.entries()].filter(([k, v]) => k && (v.length > 1 || wg.some((g) => norm(g.model) === k)))) {
  const docs = wr.filter((x) => norm(x.model).includes(k) || norm(k).includes(norm(x.model)) && norm(x.model).length > 4).map((x) => base(x.file).slice(0, 2));
  const gen = wg.filter((g) => norm(g.model) === k).map((g) => g.name);
  const ret = v.flatMap((i) => returnsForReceipt(i));
  const display = (() => { for (const rc of receipts.values()) for (const p of products(rc)) if (norm(p.model) === k) return p.model; return k; })();
  w(`| ${esc(display)} | ${[...new Set(v.map((i) => num(i)).filter(Boolean))].join(', ')} | ${[...new Set(docs)].join(', ')} | ${gen.join('; ') || ''} | ${[...new Set(ret)].join(', ')} |`);
}
w();
w('### Returns and what they return');
w();
w('| Return | Refund | About |');
w('|---|---|---|');
for (const r of returns) w(`| ${esc(base(r.file))} | ${r.refund_total} ${esc(r.refund_method)} | ${esc(r.about)} |`);
w();

w('## 6. Real phone photos (`receipts/paper-photo`)');
w();
w('| File | Store | Date | Total | Card |');
w('|---|---|---|---|---|');
for (const p of photos) w(`| ${esc(p.file)} | ${esc(p.store)} | ${p.purchase_date || ''} | ${p.total || ''} | ${p.payment_last4 || ''} |`);
w();
w('The four `1000000254` to `257` photos are also receipts 01 to 04 in the answer key (see their receipt_note).');
w();

w('## 7. Emails (separate suite)');
w();
w('| Folder | Retailers |');
w('|---|---|');
for (const d of ['order-confirmation', 'shipping', 'delivery', 'e-receipt']) {
  const rs = [...new Set(idx.filter((r) => r.path.startsWith('emails/' + d)).map((r) => r.retailer))];
  w(`| ${d} | ${rs.join(', ')} |`);
}
w();

w('## 8. Fixtures with no links');
w();
const linkedDocs = new Set(wr.map((x) => base(x.file)));
const unlinkedGeneric = wg.filter((g) => !(byModel.get(norm(g.model)) || []).length).map((g) => g.name);
const noDocPlan = order.filter((rc) => products(rc).some((p) => p.kind === 'service') && !docsForReceipt(rc.id).length).map((rc) => num(rc.id)).filter(Boolean);
w(`- Generic warranties with no same-model receipt: ${unlinkedGeneric.join(', ') || 'none'}.`);
w(`- Receipts with a plan line but no plan document built from them (candidates for more documents): ${noDocPlan.join(', ')}.`);
w(`- Warranty documents: photo twins are in warranties-from-receipts-photo (${wr.length}) and warranties-photo (${list('warranties', /.pdf$/i).length}), made by _tools/make-photo-twins.py.`);
fs.writeFileSync(path.join(R, 'INVENTORY.md'), L.join('\n') + '\n');
console.log('wrote INVENTORY.md', L.length, 'lines');
